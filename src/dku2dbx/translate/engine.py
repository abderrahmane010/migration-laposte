"""Translate the recipes of a project and write one .sql file per output."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

from dku2dbx import __version__
from dku2dbx.errors import UnsupportedConstruct
from dku2dbx.model.ir import Project, Recipe
from dku2dbx.translate.model import (
    CodeRewrite,
    ProjectTranslation,
    TranslatedOutput,
    Translation,
    Unsupported,
)
from dku2dbx.translate.registry import REWRITERS, TRANSLATORS

TO_REVIEW = "TO REVIEW: deterministic rewrite of Dataiku code, check it before production"


def translate_project(project: Project) -> ProjectTranslation:
    result = ProjectTranslation(project=project.key)
    for recipe in project.recipes:
        translator = TRANSLATORS.get(recipe.type)
        rewriter = REWRITERS.get(recipe.type)
        try:
            if translator is not None:
                result.translated.append(translator(project, recipe))
            elif rewriter is not None:
                result.rewritten.append(rewriter(project, recipe))
            else:
                result.without_translator[recipe.name] = recipe.type
        except UnsupportedConstruct as exc:
            result.unsupported.append(
                Unsupported(
                    recipe=recipe.name,
                    type=recipe.type,
                    element=exc.construct,
                    detail=exc.detail,
                )
            )
    return result


def payload_sha256(recipe: Recipe) -> str:
    """Hash of the payload as read (canonical JSON, or the raw text)."""
    if recipe.payload is not None:
        data = json.dumps(recipe.payload, sort_keys=True, separators=(",", ":"))
    else:
        data = recipe.payload_raw or ""
    return hashlib.sha256(data.encode("utf-8")).hexdigest()


def header(project: Project, recipe: Recipe, tr: Translation, out: TranslatedOutput) -> str:
    """Traceability header (CLAUDE.md, rule 3)."""
    lines = [
        f"-- Generated by dku2dbx {__version__} — do not edit by hand",
        f"-- Dataiku project: {project.key}",
        f"-- Dataiku recipe: {recipe.name} ({recipe.type})",
        f"-- Output dataset: {out.dataset}" + (" (append)" if out.append else ""),
        f"-- Recipe JSON SHA-256: {recipe.source_sha256}",
        f"-- Payload SHA-256: {payload_sha256(recipe)}",
    ]
    if tr.review:
        lines.append(f"-- {TO_REVIEW}")
    lines += [f"-- WARNING: {w}" for w in tr.warnings]
    return "\n".join(line.replace("\n", " ") for line in lines)


def python_header(project: Project, recipe: Recipe, rewrite: CodeRewrite) -> str:
    """Traceability header of a rewritten Python recipe (CLAUDE.md, rule 3)."""
    lines = [
        f"Generated by dku2dbx {__version__} — do not edit by hand",
        f"Dataiku project: {project.key}",
        f"Dataiku recipe: {recipe.name} ({recipe.type})",
        f"Recipe JSON SHA-256: {recipe.source_sha256}",
        f"Payload SHA-256: {payload_sha256(recipe)}",
        TO_REVIEW,
        *(f"WARNING: {w}" for w in rewrite.warnings),
    ]
    return "\n".join("# " + line.replace("\n", " ") for line in lines)


def sql_file_name(tr: Translation, out: TranslatedOutput) -> str:
    return f"{tr.recipe}.sql" if len(tr.outputs) == 1 else f"{tr.recipe}__{out.dataset}.sql"


def write_translation(project: Project, result: ProjectTranslation, out: Path) -> list[Path]:
    """Write <out>/<project>/sql/*.sql and translate_report.json; return the paths."""
    base = out / project.key
    sql_dir = base / "sql"
    sql_dir.mkdir(parents=True, exist_ok=True)
    py_dir = base / "python"
    py_dir.mkdir(parents=True, exist_ok=True)
    # A recipe no longer translated leaves no file.
    for stale in [*sql_dir.glob("*.sql"), *py_dir.glob("*.py")]:
        stale.unlink()
    written = []
    for tr in result.translated:
        recipe = project.recipe(tr.recipe)
        for output in tr.outputs:
            path = sql_dir / sql_file_name(tr, output)
            text = header(project, recipe, tr, output) + "\n" + output.sql.rstrip() + ";\n"
            path.write_bytes(text.encode("utf-8"))
            written.append(path)
    for rewrite in result.rewritten:
        path = py_dir / f"{rewrite.recipe}.py"
        top = python_header(project, project.recipe(rewrite.recipe), rewrite)
        path.write_bytes((top + "\n\n" + rewrite.code.rstrip() + "\n").encode("utf-8"))
        written.append(path)
    report = base / "translate_report.json"
    data = json.loads(result.model_dump_json())
    report.write_bytes(
        (json.dumps(data, indent=2, ensure_ascii=False, sort_keys=True) + "\n").encode("utf-8")
    )
    return sorted([*written, report])
