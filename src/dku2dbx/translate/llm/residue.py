REVIEW_REQUIRED = "REVIEW_REQUIRED: generated by an LLM, never run it without a human review"
PYTHON_TYPES = frozenset({"python", "pyspark"})
_BLOCK = re.compile(r"```([A-Za-z0-9_+-]*)[ \t]*\n(.*?)```", re.S)


class Status:
    READY = "ENTRÉE PRÊTE"
    """LLM disabled: the input is ready (for a later run or by hand)."""
    REVIEW = "REVIEW_REQUIRED"
    CHECK_FAILED = "REVIEW_REQUIRED, CONTRÔLE STATIQUE EN ÉCHEC"
    UNUSABLE = "RÉPONSE INEXPLOITABLE"
    ERROR = "ERREUR D'APPEL"


class LLMClient(Protocol):
    def complete(self, system: str, user: str) -> str: ...


class ResidueItem(BaseModel):
    model_config = ConfigDict(extra="forbid")

    recipe: str
    type: str
    language: str
    reason: str
    """Why the deterministic translation did not handle it."""
    prompt: str
    input_file: str
    status: str
    output_file: str | None = None
    checks: list[str] = Field(default_factory=list)


class Residue(BaseModel):
    model_config = ConfigDict(extra="forbid")

    project: str
    llm: str
    """Endpoint called, or why the LLM step is disabled."""
    items: list[ResidueItem] = Field(default_factory=list)
    deterministic_to_review: dict[str, str] = Field(default_factory=dict)
    """Recipe -> file of a deterministic rewrite to review (translate output)."""


@dataclass(frozen=True)
class Prompt:
    name: str
    text: str

    @property
    def sha256(self) -> str:
        return hashlib.sha256(self.text.encode("utf-8")).hexdigest()


def load_prompt(language: str) -> Prompt:
    """Versioned prompt of a target language (``prompts/<language>_v<N>.md``)."""
    name = f"{language}_v1"
    text = (
        resources.files("dku2dbx.translate.llm")
        .joinpath(f"prompts/{name}.md")
        .read_text(encoding="utf-8")
    )
    return Prompt(name, text)


# --------------------------------------------------------------------------- #
# Inputs
# --------------------------------------------------------------------------- #
def _language(recipe: Recipe) -> str:
    return "python" if recipe.type in PYTHON_TYPES else "sql"


def _dataset_info(
    project: Project, ref: str, branched: dict[str, str], extra: dict[str, Any]
) -> dict[str, Any]:
    info: dict[str, Any] = {"dataset": ref, "table": branched.get(ref, ref), **extra}
    try:
        dataset: Dataset | None = project.dataset(ref)
    except KeyError:
        dataset = None
    if dataset is None:
        info["columns"] = None  # shared dataset of another project: schema unknown here
        return info
    info["columns"] = [{"name": c.name, "type": c.type} for c in dataset.columns]
    info["partitioning"] = [d.name for d in dataset.partitioning]
    return info


def residue_input(
    project: Project, recipe: Recipe, reason: str, branching: Branching | None
) -> dict[str, Any]:
    """The JSON sent to the LLM: configuration only, never data (exports have none)."""
    branched = dict(branching.resolved) if branching else {}
    data: dict[str, Any] = {
        "dku2dbx_version": __version__,
        "project": project.key,
        "recipe": {
            "name": recipe.name,
            "type": recipe.type,
            "engine": recipe.engine,
            "params": recipe.params,
        },
        "inputs": [
            _dataset_info(project, i.ref, branched, {"partition_dependencies": i.deps})
            for i in recipe.inputs
        ],
        "outputs": [
            _dataset_info(project, o.ref, branched, {"append": o.append_mode})
            for o in recipe.outputs
        ],
        "job_parameters": {name: parameter_name(name) for name in sorted(project.variables)},
        "deterministic_refusal": reason,
    }
    if recipe.payload_raw is not None:
        data["code"] = recipe.payload_raw
    else:
        data["payload"] = recipe.payload
    types = set()
    for inp in recipe.inputs:
        try:
            types.add(project.dataset(inp.ref).type)
        except KeyError:
            continue
    if len(types) == 1:
        data["source_dialect"] = DIALECTS.get(types.pop())
    return data


def residual_recipes(project: Project, result: ProjectTranslation) -> dict[str, str]:
    """Recipe -> reason, for the LLM_REVIEW recipes not handled deterministically."""
    done = {t.recipe for t in result.translated} | {r.recipe for r in result.rewritten}
    refused = {u.recipe: f"{u.element} — {u.detail}" for u in result.unsupported}
    residue = {}
    for c in classify(project):
        if c.target_class is not TargetClass.LLM_REVIEW or c.name in done:
            continue
        default = (
            "pas de traducteur déterministe"
            if c.type in LLM_CODE_TYPES
            else "; ".join(c.reasons) or "pas de traducteur déterministe"
        )
        residue[c.name] = refused.get(c.name, default)
    return residue


