def extract_code(answer: str, language: str) -> str | None:
    """The single fenced block of the expected language, else None (never guessed)."""
    blocks = [(lang.lower(), body) for lang, body in _BLOCK.findall(answer)]
    aliases = {"python": {"python", "py"}, "sql": {"sql", "sparksql", "databricks"}}
    matching = [body for lang, body in blocks if lang in aliases[language]]
    if len(blocks) != 1 or len(matching) != 1:
        return None
    return str(matching[0]).strip() + "\n"


def _ruff(code: str) -> str | None:
    """Errors found by ruff (syntax, undefined names...), None when ruff is absent."""
    ruff = shutil.which("ruff")
    if ruff is None:
        return None
    run = subprocess.run(
        [
            ruff,
            "check",
            "--no-cache",
            "--isolated",
            "--select",
            "E9,F",
            "--stdin-filename",
            "llm_output.py",
            "-",
        ],
        input=code,
        capture_output=True,
        text=True,
        check=False,
    )
    return "" if run.returncode == 0 else run.stdout.strip()


def _python_checks(code: str) -> tuple[bool, list[str]]:
    try:
        module = ast.parse(code)
    except SyntaxError as exc:
        return False, [f"ast : erreur de syntaxe ligne {exc.lineno} ({exc.msg})"]
    lines = ["ast : OK"]
    names = {n.id for n in ast.walk(module) if isinstance(n, ast.Name)}
    imports = {
        a.name.split(".")[0] for n in ast.walk(module) if isinstance(n, ast.Import) for a in n.names
    }
    if "dataiku" in names | imports:
        return False, [*lines, "appels dataiku restants"]
    ruff = _ruff(code)
    if ruff is None:
        return True, [*lines, "ruff : non installé, non vérifié"]
    # spark, dbutils and display are defined by the notebook runtime.
    errors = [
        line
        for line in ruff.splitlines()
        if re.search(r"\b(E9\d\d|F\d+)\b", line)
        and not ("F821" in line and re.search(r"`(spark|dbutils|display)`", line))
    ]
    if errors:
        return False, [*lines, f"ruff : {len(errors)} erreur(s)", *errors[:10]]
    return True, [*lines, "ruff : OK"]


def _sql_checks(code: str) -> tuple[bool, list[str]]:
    try:
        statements = [s for s in sqlglot.parse(code, read="databricks") if s is not None]
    except ParseError as exc:
        return False, [f"sqlglot : SQL illisible ({str(exc).splitlines()[0]})"]
    if not statements:
        return False, ["sqlglot : aucune instruction"]
    lines = [f"sqlglot : OK ({len(statements)} instruction(s))"]
    unknown = sorted({f.name for s in statements for f in s.find_all(exp.Anonymous)})
    if unknown:
        lines.append(f"fonctions inconnues de sqlglot, à vérifier : {', '.join(unknown)}")
    return True, lines


def static_checks(code: str, language: str) -> tuple[bool, list[str]]:
    """(passed, check lines for the header and the report); the code is never run."""
    return _python_checks(code) if language == "python" else _sql_checks(code)


def output_header(
    project: Project, recipe: Recipe, config: LLMConfig, prompt: Prompt, checks: list[str]
) -> str:
    """Traceability header (CLAUDE.md, rule 3) with REVIEW_REQUIRED (rule 1)."""
    lines = [
        REVIEW_REQUIRED,
        f"Generated by dku2dbx {__version__} (LLM residue, phase 8)",
        f"Dataiku project: {project.key}",
        f"Dataiku recipe: {recipe.name} ({recipe.type})",
        f"Recipe JSON SHA-256: {recipe.source_sha256}",
        f"Payload SHA-256: {payload_sha256(recipe)}",
        f"Model Serving endpoint: {config.endpoint}",
        f"Prompt: {prompt.name} (SHA-256 {prompt.sha256})",
        *(f"Static check: {c}" for c in checks),
    ]
    mark = "# " if _language(recipe) == "python" else "-- "
    return "\n".join(mark + line.replace("\n", " ") for line in lines)


# --------------------------------------------------------------------------- #
# Run
# --------------------------------------------------------------------------- #
def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.encode("utf-8"))


def run_residue(
    project: Project,
    config: LLMConfig,
    out: Path,
    *,
    client: LLMClient | None = None,
    branching: Branching | None = None,
) -> Residue:
    """Write <out>/inputs/*.json, and <out>/outputs/* when the LLM is enabled."""
    result = translate_project(project)
    for stale in [*out.glob("inputs/*.json"), *out.glob("outputs/*")]:
        stale.unlink()
    llm = (
        f"endpoint {config.endpoint} ({config.source})"
        if config.enabled and client is not None
        else f"désactivé : aucun endpoint validé dans {config.source}"
    )
    residue = Residue(project=project.key, llm=llm)
    for name, reason in sorted(residual_recipes(project, result).items()):
        recipe = project.recipe(name)
        language = _language(recipe)
        prompt = load_prompt(language)
        data = residue_input(project, recipe, reason, branching)
        user = json.dumps(data, indent=2, ensure_ascii=False, sort_keys=True) + "\n"
        input_file = f"inputs/{name}.json"
        _write(out / input_file, user)
        item = ResidueItem(
            recipe=name,
            type=recipe.type,
            language=language,
            reason=reason,
            prompt=prompt.name,
            input_file=input_file,
            status=Status.READY,
        )
        residue.items.append(item)
        if not config.enabled or client is None:
            continue
        try:
            answer = client.complete(prompt.text, user)
        except Exception as exc:  # network, permissions, quota...: reported, never fatal
            item.status = Status.ERROR
            item.checks = [f"{type(exc).__name__}: {str(exc)[:200]}"]
            continue
        code = extract_code(answer, language)
        if code is None:
            item.status = Status.UNUSABLE
            item.checks = [f"un seul bloc de code {language} attendu"]
            continue
        passed, item.checks = static_checks(code, language)
        item.status = Status.REVIEW if passed else Status.CHECK_FAILED
        item.output_file = f"outputs/{name}.{'py' if language == 'python' else 'sql'}"
        header = output_header(project, recipe, config, prompt, item.checks)
        _write(out / item.output_file, header + "\n\n" + code)
    for t in result.translated:
        if t.review:
            residue.deterministic_to_review[t.recipe] = f"sql/{t.recipe}.sql"
    for r in result.rewritten:
        residue.deterministic_to_review[r.recipe] = f"python/{r.recipe}.py"
    return residue


def serving_client(config: LLMConfig) -> LLMClient:  # pragma: no cover (no endpoint yet)
    """Client of the Model Serving endpoint (databricks-sdk, optional dependency)."""
    try:
        from databricks.sdk import WorkspaceClient  # type: ignore[import-not-found]  # noqa: PLC0415
        from databricks.sdk.service.serving import (  # type: ignore[import-not-found]  # noqa: PLC0415
            ChatMessage,
            ChatMessageRole,
        )
    except ImportError as exc:
        raise RuntimeError("databricks-sdk is not installed: uv add databricks-sdk") from exc
    workspace = WorkspaceClient(profile=config.profile)

    class _Serving:
        def complete(self, system: str, user: str) -> str:
            response = workspace.serving_endpoints.query(
                name=config.endpoint,
                messages=[
                    ChatMessage(role=ChatMessageRole.SYSTEM, content=system),
                    ChatMessage(role=ChatMessageRole.USER, content=user),
                ],
                max_tokens=config.max_tokens,
                temperature=config.temperature,
            )
            return str(response.choices[0].message.content)

    return _Serving()
