"""Generate the reconciliation notebook, its plan and the registry of accepted differences.

The notebook compares every table the migrated flow materializes (outputs of the
simplified steps, phase 5) with the Dataiku output of the same dataset. ASSUMPTION
(ROADMAP phase 9, H-60): the Dataiku outputs are readable in Unity Catalog, by
default as ``<ref_catalog>.<ref_schema>.<dataset>`` (job parameters), or at the
``reference`` given in config/reconcile.yaml. The Databricks side is
``<catalog>.<schema>.<dataset>``, as written by the bundle (phase 6).

The notebook is self-contained: the comparison module (``compare.py``) is copied into
it, so nothing has to be installed on the workspace.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass, field
from importlib import resources
from pathlib import Path
from typing import Any

from dku2dbx import __version__
from dku2dbx.generate.bundle import PY_CELL, PY_NOTEBOOK_HEADER
from dku2dbx.model.ir import Project
from dku2dbx.reconcile.config import ReconcileConfig
from dku2dbx.simplify.flow import simplify_flow

NOTEBOOK = "reconcile.py"
PLAN = "RECONCILIATION.md"
REGISTRY = "ECARTS_ACCEPTES.md"
RESULTS_TABLE = "dku2dbx_reconciliation"
DECISIONS = ("corriger", "reproduire l'ancien comportement")


@dataclass
class Reconciliation:
    project: str
    specs: list[dict[str, Any]]
    skipped: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    source: str = ""


def plan_reconciliation(project: Project, config: ReconcileConfig, source: str) -> Reconciliation:
    """Which tables to compare, with which key and tolerances."""
    flow = simplify_flow(project)
    outputs = [dataset for step in flow.steps for dataset in step.outputs]
    plan = Reconciliation(project=project.key, specs=[], source=source)
    for name in sorted(set(config.tables) - set(outputs)):
        plan.warnings.append(f"{name} : déclarée dans la configuration, mais pas produite")
    for name in outputs:
        rule = config.rule(name)
        if rule.get("skip"):
            plan.skipped.append(name)
            continue
        dataset = project.dataset(name)
        partitions = rule.get("partition_columns", [d.name for d in dataset.partitioning])
        spec = {
            "dataset": name,
            "key": rule.get("key", []),
            "abs_tolerance": rule.get("abs_tolerance", 0.0),
            "rel_tolerance": rule.get("rel_tolerance", 0.0),
            "ignore_columns": rule.get("ignore_columns", []),
            "partition_columns": partitions,
            "reference": rule.get("reference"),
            "source_sha256": dataset.source_sha256,
        }
        if not spec["key"] and (spec["abs_tolerance"] or spec["rel_tolerance"]):
            plan.warnings.append(
                f"{name} : tolérance sans clé, la comparaison ligne à ligne reste exacte"
            )
        plan.specs.append(spec)
    return plan


def _compare_source() -> str:
    text = resources.files("dku2dbx.reconcile").joinpath("compare.py").read_text("utf-8")
    # Each notebook cell is compiled alone: a __future__ import is only legal on top.
    return text.replace("from __future__ import annotations\n", "")


def specs_sha256(plan: Reconciliation) -> str:
    return hashlib.sha256(json.dumps(plan.specs, sort_keys=True).encode("utf-8")).hexdigest()


def reconcile_notebook(plan: Reconciliation) -> str:
    header = [
        f"Generated by dku2dbx {__version__}: reconciliation of the Dataiku project "
        f"{plan.project} (phase 9)",
        f"Configuration: {plan.source} (tables SHA-256 {specs_sha256(plan)})",
        *(f"Dataset {s['dataset']}: JSON SHA-256 {s['source_sha256']}" for s in plan.specs),
        "Compares each Dataiku output with the Databricks table of the same dataset:",
        "schema, row counts, aggregates, rows. Fails when a table is in ÉCART.",
    ]
    tables = [{k: v for k, v in s.items() if k != "source_sha256"} for s in plan.specs]
    cells = [
        PY_NOTEBOOK_HEADER + "\n" + "\n".join(f"# {line}" for line in header),
        "\n".join(
            [
                f"PROJECT = {plan.project!r}",
                'dbutils.widgets.text("catalog", "")',
                'dbutils.widgets.text("schema", "")',
                'dbutils.widgets.text("ref_catalog", "")',
                'dbutils.widgets.text("ref_schema", "")',
                f'dbutils.widgets.text("results_table", "{RESULTS_TABLE}")',
                'CATALOG = dbutils.widgets.get("catalog")',
                'SCHEMA = dbutils.widgets.get("schema")',
                'REF_CATALOG = dbutils.widgets.get("ref_catalog")',
                'REF_SCHEMA = dbutils.widgets.get("ref_schema")',
                'RESULTS_TABLE = dbutils.widgets.get("results_table")',
                "if not (CATALOG and SCHEMA):",
                '    raise ValueError("dku2dbx: the catalog and schema parameters are required")',
            ]
        ),
        "# Comparison module of dku2dbx (src/dku2dbx/reconcile/compare.py), copied as is.\n"
        + _compare_source().rstrip("\n"),
        "import json\n\nTABLES = json.loads(" + repr(json.dumps(tables, sort_keys=True)) + ")",
        "\n".join(
            [
                "def _name(*parts):",
                '    return ".".join(f"`{p}`" for p in parts)',
                "",
                "",
                "results = []",
                "for spec in TABLES:",
                "    if spec.get('reference'):",
                "        reference = spec['reference']",
                "    elif REF_CATALOG and REF_SCHEMA:",
                "        reference = _name(REF_CATALOG, REF_SCHEMA, spec['dataset'])",
                "    else:",
                "        error = 'ref_catalog/ref_schema vides'",
                "        results.append(missing_table(spec, 'Dataiku', error))",
                "        continue",
                "    try:",
                "        ref = spark.table(reference)",
                "    except Exception as exc:  # absent or unreadable: an ÉCART, never a crash",
                "        results.append(missing_table(spec, 'Dataiku', str(exc)))",
                "        continue",
                "    try:",
                "        new = spark.table(_name(CATALOG, SCHEMA, spec['dataset']))",
                "    except Exception as exc:",
                "        results.append(missing_table(spec, 'Databricks', str(exc)))",
                "        continue",
                "    results.append(reconcile_table(ref, new, spec))",
                "",
                "REPORT = report_markdown(PROJECT, results)",
                "print(REPORT)",
            ]
        ),
        "\n".join(
            [
                "from datetime import datetime, timezone",
                "",
                'RUN_AT = datetime.now(timezone.utc).isoformat(timespec="seconds")',
                "rows = [",
                "    (PROJECT, r['table'], r['status'], len(r['differences']),",
                "     json.dumps(r['differences'], ensure_ascii=False), RUN_AT)",
                "    for r in results",
                "]",
                "spark.createDataFrame(",
                "    rows,",
                '    "project string, table string, status string, differences int, '
                'details string, run_at string",',
                ').write.mode("append").saveAsTable(_name(CATALOG, SCHEMA, RESULTS_TABLE))',
            ]
        ),
        "\n".join(
            [
                "failed = [r['table'] for r in results if r['status'] == DIFFERENT]",
                "if failed:",
                "    raise AssertionError(",
                '        "dku2dbx: reconciliation in ÉCART for " + ", ".join(failed)',
                '        + " (details in " + RESULTS_TABLE + ")"',
                "    )",
                "dbutils.notebook.exit(results_json(results))",
            ]
        ),
    ]
    return PY_CELL.join(cells) + "\n"


def plan_markdown(plan: Reconciliation) -> str:
    lines = [
        f"# Plan de réconciliation — {plan.project}",
        "",
        f"Généré par dku2dbx {__version__}. Configuration : `{plan.source}`.",
        "",
        f"Le notebook `{NOTEBOOK}` compare chaque table produite par le flux migré avec la "
        "sortie Dataiku du même dataset, en quatre couches : schéma, nombre de lignes "
        "(au total et par partition), agrégats par colonne, puis lignes. Il écrit un "
        f"résultat par table dans `<catalog>.<schema>.{RESULTS_TABLE}` (Delta) et échoue "
        "si une table est en ÉCART.",
        "",
        "Paramètres : `catalog`, `schema` (tables Databricks), `ref_catalog`, `ref_schema` "
        "(sorties Dataiku dans Unity Catalog), `results_table`.",
        "",
        f"- Tables comparées : **{len(plan.specs)}**",
        f"- Tables exclues (`skip`) : **{len(plan.skipped)}**",
        "",
        "| Table | Clé | Tolérance abs. | Tolérance rel. | Partitions | Colonnes ignorées "
        "| Référence Dataiku |",
        "|---|---|---|---|---|---|---|",
    ]
    for s in plan.specs:
        key = ", ".join(s["key"]) or "aucune (EXCEPT ALL)"
        reference = s["reference"] or f"`<ref_catalog>.<ref_schema>.{s['dataset']}`"
        lines.append(
            f"| {s['dataset']} | {key} | {s['abs_tolerance']} | {s['rel_tolerance']} "
            f"| {', '.join(s['partition_columns']) or '—'} "
            f"| {', '.join(s['ignore_columns']) or '—'} | {reference} |"
        )
    if plan.skipped:
        lines += ["", "## Exclues", "", *(f"- {name}" for name in plan.skipped)]
    if plan.warnings:
        lines += ["", "## À vérifier", "", *(f"- {w}" for w in plan.warnings)]
    return "\n".join(lines) + "\n"


def registry_markdown(plan: Reconciliation) -> str:
    """Template of the registry of accepted differences (ROADMAP phase 9, task 3)."""
    lines = [
        f"# Registre des écarts acceptés — {plan.project}",
        "",
        f"Gabarit généré par dku2dbx {__version__}, **à remplir par le métier** après "
        "chaque réconciliation. dku2dbx ne réécrit jamais ce fichier.",
        "",
        "Une ligne par écart constaté (statut ÉCART ou ÉCART TOLÉRÉ). Décision :",
        "",
        "- **corriger** : le comportement Databricks est le bon, l'écart est accepté "
        "(par exemple, un défaut de Dataiku corrigé par la migration) ;",
        "- **reproduire l'ancien comportement** : le code migré doit être modifié pour "
        "donner le même résultat que Dataiku.",
        "",
        "| Table | Couche | Écart constaté | Décision | Justification métier | Décideur | Date |",
        "|---|---|---|---|---|---|---|",
        *(f"| {s['dataset']} | | | | | | |" for s in plan.specs),
    ]
    return "\n".join(lines) + "\n"


def write_reconciliation(plan: Reconciliation, out: Path) -> list[Path]:
    """Write the notebook and the plan; the registry only if it does not exist yet."""
    out.mkdir(parents=True, exist_ok=True)
    files = {NOTEBOOK: reconcile_notebook(plan), PLAN: plan_markdown(plan)}
    written = []
    for name, text in files.items():
        (out / name).write_bytes(text.encode("utf-8"))
        written.append(out / name)
    registry = out / REGISTRY
    if not registry.exists():  # filled by people: never overwritten
        registry.write_bytes(registry_markdown(plan).encode("utf-8"))
        written.append(registry)
    return written
