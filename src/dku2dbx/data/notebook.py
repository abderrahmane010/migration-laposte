"""Copy notebooks and report of the dataset migration (phase 11).

One self-contained Python notebook per dataset to copy (``COPIE`` or ``HISTORIQUE``):
the runtime ``load.py`` is copied into it. It writes ``<catalog>.<schema>.<dataset>``
(job parameters, as the bundle does), idempotently, then validates the table and
fails when a problem remains.
"""

from __future__ import annotations

import json
from collections import Counter
from importlib import resources
from pathlib import Path

from dku2dbx import __version__
from dku2dbx.data.plan import DataPlan, DatasetDecision, Federation, Strategy
from dku2dbx.generate.bundle import PY_CELL, PY_NOTEBOOK_HEADER

REPORT = "donnees.md"
PLAN_JSON = "donnees.json"
NOTEBOOKS = "notebooks"


def _load_source() -> str:
    text = resources.files("dku2dbx.data").joinpath("load.py").read_text("utf-8")
    # Each notebook cell is compiled alone: a __future__ import is only legal on top.
    return text.replace("from __future__ import annotations\n", "")


def notebook_name(decision: DatasetDecision) -> str:
    return f"copie_{decision.uc_name}.py"


def copy_notebook(plan: DataPlan, decision: DatasetDecision) -> str:
    if decision.strategy not in (Strategy.COPY, Strategy.HISTORY) or decision.read is None:
        raise ValueError(f"{decision.dataset}: nothing to copy ({decision.strategy})")
    sha = decision.properties.get("dku2dbx.dataiku.json_sha256", "?")
    header = [
        f"Generated by dku2dbx {__version__} — do not edit by hand",
        f"Dataiku project: {plan.project}",
        f"Dataset {decision.dataset}: JSON SHA-256 {sha}",
        f"Strategy: {decision.strategy} — {decision.reason}",
        f"Writes <catalog>.<schema>.{decision.uc_name}, then validates schema, types, "
        "partitions, rows and metadata.",
        "Idempotent: mode=skip (default) never rewrites loaded rows and only adds missing",
        "partitions; mode=replace replaces the whole table (explicit request only).",
    ]
    spec = decision.model_dump(
        include={"dataset", "read", "columns", "partition_column", "properties", "column_mapping"}
    )
    cells = [
        PY_NOTEBOOK_HEADER + "\n" + "\n".join(f"# {line}" for line in header),
        "\n".join(
            [
                'dbutils.widgets.text("catalog", "")',
                'dbutils.widgets.text("schema", "")',
                'dbutils.widgets.text("mode", "skip")',
                'CATALOG = dbutils.widgets.get("catalog")',
                'SCHEMA = dbutils.widgets.get("schema")',
                'MODE = dbutils.widgets.get("mode")',
                "if not (CATALOG and SCHEMA):",
                '    raise ValueError("dku2dbx: the catalog and schema parameters are required")',
            ]
        ),
        "# Copy module of dku2dbx (src/dku2dbx/data/load.py), copied as is.\n"
        + _load_source().rstrip("\n"),
        "\n".join(
            [
                "import json",
                "",
                "SPEC = json.loads(" + repr(json.dumps(spec, sort_keys=True)) + ")",
                'SPEC["target"] = ".".join(',
                '    "`" + p.replace("`", "``") + "`" for p in (CATALOG, SCHEMA, '
                f"{decision.uc_name!r})",
                ")",
            ]
        ),
        "\n".join(
            [
                "RESULT = copy_dataset(spark, SPEC, MODE)",
                "print(json.dumps(RESULT, ensure_ascii=False, indent=2))",
                'if RESULT["problems"]:',
                "    raise AssertionError(",
                '        "dku2dbx: " + SPEC["dataset"] + " does not match its Dataiku dataset: "',
                '        + "; ".join(RESULT["problems"])',
                "    )",
                "dbutils.notebook.exit(json.dumps(RESULT, ensure_ascii=False))",
            ]
        ),
    ]
    return PY_CELL.join(cells) + "\n"


def _cell(text: str | None) -> str:
    return (text or "—").replace("|", "\\|")


def report_markdown(plan: DataPlan, permissions: dict[str, list[str]] | None = None) -> str:
    counts = Counter(d.strategy for d in plan.decisions)
    federation = Counter(d.federation for d in plan.decisions if d.federation.value != "—")
    lines = [
        f"# Migration des datasets — {plan.project}",
        "",
        f"Généré par dku2dbx {__version__}. Configuration : `{plan.source}`.",
        "",
        "Rien n'est copié par défaut : chaque dataset reçoit une décision explicite. "
        "`REFUSÉ` signifie qu'aucune copie n'est générée tant que la raison n'est pas "
        "levée (en général : compléter `config/data.local.yaml`).",
        "",
        "## Synthèse",
        "",
        *(f"- {s.value} : **{counts[s]}**" for s in Strategy if counts[s]),
        "",
        "## Décision par dataset",
        "",
        "| Dataset | Rôle | Décision | Federation | Table Unity Catalog | Raison |",
        "|---|---|---|---|---|---|",
    ]
    lines += [
        f"| {_cell(d.dataset)} | {d.role} | {d.strategy.value} | {d.federation.value} "
        f"| {_cell(d.reference or d.uc_name)} | {_cell(d.reason)} |"
        for d in plan.decisions
    ]
    lines += ["", "## Lakehouse Federation", ""]
    if federation:
        lines += [
            "Aucune connexion n'est supposée compatible : seul `COMPATIBLE` (type pris en "
            "charge **et** connexion déclarée `federation: available` avec son "
            "`foreign_catalog`) permet de lire ou de copier par Federation.",
            "",
            *(f"- {f.value} : {federation[f]} dataset(s)" for f in Federation if federation[f]),
        ]
        pending = sorted(
            {
                str(plan_ds.properties.get("dku2dbx.dataiku.connection"))
                for plan_ds in plan.decisions
                if plan_ds.federation is Federation.TO_CONFIRM
            }
        )
        if pending:
            lines += ["", f"Connexions à confirmer avec l'équipe plateforme : {', '.join(pending)}"]
    else:
        lines.append("Aucune source base de données.")
    renamed = [d for d in plan.decisions if d.name_note]
    lines += ["", "## Noms", ""]
    lines.append(
        "Chaque table porte le nom de son dataset Dataiku ; les identifiants originaux "
        "(projet, dataset, recette, connexion, table ou chemin, hash) sont enregistrés dans "
        "ses propriétés `dku2dbx.dataiku.*` et dans `donnees.json`."
    )
    if renamed:
        lines += ["", "Noms inutilisables tels quels (datasets refusés, renommage à décider) :", ""]
        lines += [f"- {d.dataset} : {d.name_note} → proposition `{d.uc_name}`" for d in renamed]
    copies = plan.copies
    lines += ["", "## Copies", ""]
    if copies:
        lines += [
            f"Notebooks dans `{NOTEBOOKS}/`, paramètres `catalog`, `schema` et `mode`. "
            "Par défaut (`mode=skip`), une table déjà chargée n'est pas réécrite et seules "
            "les partitions absentes sont ajoutées : la copie se relance sans doublon. "
            "`mode=replace` remplace toute la table, sur demande explicite seulement.",
            "",
            "Après chaque copie, le notebook valide le schéma, les types, les partitions, "
            "le nombre de lignes et les métadonnées, et échoue s'il reste un problème.",
            "",
            *(f"- `{NOTEBOOKS}/{notebook_name(d)}` : {d.dataset}" for d in copies),
        ]
    else:
        lines.append("(aucune)")
    lines += ["", "## Permissions", ""]
    if permissions is None:
        lines.append(
            "Non vérifiées (pas d'accès Databricks : option `--check-uc`). Chaque copie "
            "échoue clairement si la source n'est pas lisible ou le schéma cible pas "
            "inscriptible."
        )
    elif not any(permissions.values()):
        lines.append("Vérifiées : aucun droit manquant.")
    else:
        lines += [
            f"- {name} : {'; '.join(missing)}" for name, missing in permissions.items() if missing
        ]
    return "\n".join(lines) + "\n"


def write_data(
    plan: DataPlan, out: Path, permissions: dict[str, list[str]] | None = None
) -> list[Path]:
    """Write the report, the plan and one notebook per copy, removing stale notebooks."""
    files = {
        REPORT: report_markdown(plan, permissions),
        PLAN_JSON: json.dumps(json.loads(plan.model_dump_json()), indent=2, ensure_ascii=False)
        + "\n",
    }
    files.update({f"{NOTEBOOKS}/{notebook_name(d)}": copy_notebook(plan, d) for d in plan.copies})
    stale = out / NOTEBOOKS
    if stale.is_dir():
        for old in stale.glob("copie_*.py"):
            old.unlink()
    written = []
    for name, text in sorted(files.items()):
        path = out / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(text.encode("utf-8"))
        written.append(path)
    return written
