def test_schema_still_rejects_errors(bundle_schema: dict[str, Any]) -> None:
    """The adapted schema is not a no-op: a wrong field or level is still rejected."""
    validator = jsonschema.validators.validator_for(bundle_schema)(bundle_schema)
    assert list(validator.iter_errors({"resources": {"jobs": {"j": {"taks": []}}}}))  # typo
    assert list(validator.iter_errors({"resources": {"jobs": {"j": {"tasks": [{"key": "t"}]}}}}))
    assert list(validator.iter_errors({"permissions": [{"level": 42}]}))
