SCHEMA_FILE = Path(__file__).parent / "schemas" / "databricks_bundle_schema_cli_1.24.0.json.gz"


def _adapt(node: Any) -> Any:
    """Two documented adaptations of the official schema (written for editors):

    - its ``\\p{...}`` patterns are unknown to Python's ``re``: only those are dropped;
    - its ``oneOf`` alternatives overlap (any string, for ``${var.x}``, and an enum):
      a valid value matches both, so ``oneOf`` is read as ``anyOf``.
    """
    if isinstance(node, dict):
        return {
            ("anyOf" if k == "oneOf" else k): _adapt(v)
            for k, v in node.items()
            if not (k == "pattern" and isinstance(v, str) and "\\p{" in v)
        }
    if isinstance(node, list):
        return [_adapt(v) for v in node]
    return node


