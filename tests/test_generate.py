SCHEMA_FILE = Path(__file__).parent / "schemas" / "databricks_bundle_schema_cli_1.24.0.json.gz"


def _adapt(node: Any) -> Any:
    """Two documented adaptations of the official schema (written for editors):

    - its ``\\p{...}`` patterns are unknown to Python's ``re``: only those are dropped;
    - its ``oneOf`` alternatives overlap (any string, for ``${var.x}``, and an enum):
      a valid value matches both, so ``oneOf`` is read as ``anyOf``.
    """
    if isinstance(node, dict):
        return {
            ("anyOf" if k == "oneOf" else k): _adapt(v)
            for k, v in node.items()
            if not (k == "pattern" and isinstance(v, str) and "\\p{" in v)
        }
    if isinstance(node, list):
        return [_adapt(v) for v in node]
    return node


@pytest.fixture(scope="module")
def bundle_schema() -> dict[str, Any]:
    with gzip.open(SCHEMA_FILE) as f:
        schema: dict[str, Any] = _adapt(json.load(f))
    return schema


@pytest.mark.parametrize("key", ["DEMO_SIMPLE", "DEMO_COMPLEXE"])
@pytest.mark.parametrize("name", ["databricks.yml", "resources/job.yml"])
def test_bundle_files_match_the_official_schema(
    key: str, name: str, bundle_schema: dict[str, Any]
) -> None:
    """Local validation (decision of 2026-11-23): Databricks CLI 1.24.0 bundle schema."""
    document = yaml.safe_load(generate_job_bundle(fixture(key)).files[name])
    validator = jsonschema.validators.validator_for(bundle_schema)(bundle_schema)
    errors = sorted(validator.iter_errors(document), key=lambda e: list(e.path))
    assert errors == [], [f"{list(e.path)}: {e.message}" for e in errors]
    # The root of the official schema accepts unknown keys: check them here.
    assert set(document) <= set(bundle_schema["properties"])


