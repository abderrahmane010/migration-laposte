# End to end: the DEMO_SIMPLE job on PySpark, in task order
# --------------------------------------------------------------------------- #
_CREATE = re.compile(r"^CREATE OR REPLACE TABLE `([^`]+)` AS\n(.*);$", re.S)


def run_job_locally(spark: Any, bundle_files: dict[str, str]) -> None:
    """Run the notebooks in job order; tables become temp views (no catalog locally)."""
    job = yaml.safe_load(bundle_files["resources/job.yml"])["resources"]["jobs"]
    [definition] = job.values()
    done: set[str] = set()
    tasks = {t["task_key"]: t for t in definition["tasks"]}
    while len(done) < len(tasks):
        ready = [
            k
            for k, t in tasks.items()
            if k not in done and all(d["task_key"] in done for d in t.get("depends_on", []))
        ]
        assert ready, "the job has a dependency cycle"
        for key in sorted(ready):
            path = tasks[key]["notebook_task"]["notebook_path"].removeprefix("../")
            for cell in bundle_files[path].split(CELL)[1:]:
                if cell.startswith(("USE ", "CREATE SCHEMA")):
                    continue
                match = _CREATE.match(cell.strip())
                assert match, f"unexpected statement in {path}: {cell[:60]}"
                spark.sql(match.group(2)).createOrReplaceTempView(match.group(1))
            done.add(key)


@pytest.mark.spark
def test_demo_simple_runs_end_to_end_on_spark(spark: Any) -> None:
    d0, d1, d2 = (datetime(2026, 1, day) for day in (1, 2, 3))
    orders = "order_id long, customer_id long, order_date timestamp, amount double, status string"
    spark.createDataFrame(
        [(1, 10, d1, 10.004, "NEW"), (2, 10, d2, 5.0, "CANCELLED"), (3, 20, d1, 7.5, None)], orders
    ).createOrReplaceTempView("orders_raw")
    spark.createDataFrame([(9, 10, d0, 3.0, "OLD")], orders).createOrReplaceTempView(
        "orders_archive"
    )
    spark.createDataFrame(
        [(10, "Ann", "B2B"), (20, "Bob", "B2C")], "customer_id long, name string, segment string"
    ).createOrReplaceTempView("customers")

    run_job_locally(spark, generate_job_bundle(fixture("DEMO_SIMPLE")).files)

    # Computed by hand: order 2 is CANCELLED (removed), order 3 status becomes UNKNOWN,
    # the archive has no amount_eur (NULL, ignored by SUM/AVG but counted by COUNT(*)).
    stats = sorted(tuple(r) for r in spark.table("customer_stats").collect())
    assert stats == [(10, 2, 10.0, 10.0), (20, 1, 7.5, 7.5)]
    ranked = sorted(
        (r["order_id"], r["status"], r["rank"], r["amount_eur_sum"])
        for r in spark.table("orders_ranked").collect()
    )
    assert ranked == [(1, "NEW", 2, 10.0), (3, "UNKNOWN", 1, 7.5), (9, "OLD", 1, 10.0)]


