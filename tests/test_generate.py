def test_bundle_is_byte_reproducible(tmp_path: Path) -> None:
    for run in ("a", "b"):
        write_bundle(generate_job_bundle(fixture("DEMO_COMPLEXE")), tmp_path / run)
    for path in sorted((tmp_path / "a").rglob("*")):
        if path.is_file():
            assert (
                path.read_bytes()
                == (tmp_path / "b" / path.relative_to(tmp_path / "a")).read_bytes()
            )


